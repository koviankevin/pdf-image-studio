import {createHash} from 'node:crypto';
import {readFile,readdir,writeFile} from 'node:fs/promises';
import {fileURLToPath,pathToFileURL} from 'node:url';
import path from 'node:path';
import {PRODUCT_VERSION,RELEASE_DATE} from '../dist/product-core.mjs';

const root=fileURLToPath(new URL('../dist/',import.meta.url)),generated=new Set(['release.json','release-manifest.json','release-info.mjs']);
export function canonicalBytes(data){
  // Git checkouts on Windows can use CRLF. The release format explicitly hashes
  // valid UTF-8 text with LF and binary bytes unchanged on every platform.
  if(data.includes(0))return data;const text=data.toString('utf8');return Buffer.from(text,'utf8').equals(data)?Buffer.from(text.replace(/\r\n/g,'\n'),'utf8'):data;
}
const digest=data=>createHash('sha256').update(data).digest('hex');
export async function releaseManifest(){
  const assets=[];
  async function walk(directory,prefix=''){
    for(const entry of await readdir(directory,{withFileTypes:true})){
      const name=prefix+entry.name;if(generated.has(name))continue;
      if(entry.isSymbolicLink())throw Error('Release assets must not be symlinks: '+name);
      if(entry.isDirectory())await walk(path.join(directory,entry.name),name+'/');
      else if(entry.isFile()){const bytes=canonicalBytes(await readFile(path.join(directory,entry.name)));assets.push({file:name,size:bytes.length,sha256:digest(bytes)});}
    }
  }
  await walk(root);assets.sort((a,b)=>a.file<b.file?-1:a.file>b.file?1:0);
  const info={version:PRODUCT_VERSION,date:RELEASE_DATE,channel:'stable',buildId:digest(JSON.stringify(assets)),files:assets.length};
  return {info,manifest:{format:'shijian-release',version:1,canonicalization:'utf8-lf-binary-raw',...info,assets}};
}
export async function writeRelease({check=false}={}){
  const {info,manifest}=await releaseManifest();
  const entries=[['release.json',JSON.stringify(info,null,2)+'\n'],['release-manifest.json',JSON.stringify(manifest,null,2)+'\n'],['release-info.mjs','// Generated by scripts/release-manifest.mjs.\nexport const release=Object.freeze('+JSON.stringify(info)+');\n']];
  for(const [name,text]of entries){if(check){const actual=(await readFile(path.join(root,name),'utf8')).replace(/\r\n/g,'\n');if(actual!==text)throw Error('Release manifest is stale: '+name+'. Run node scripts/release-manifest.mjs');}else await writeFile(path.join(root,name),text);}
  return info;
}
if(process.argv[1]&&pathToFileURL(path.resolve(process.argv[1])).href===import.meta.url){
  try{const info=await writeRelease({check:process.argv.includes('--check')});console.log(`${process.argv.includes('--check')?'Verified':'Generated'} release ${info.version}, ${info.files} assets, build ${info.buildId.slice(0,12)}.`);}catch(error){console.error(error.message);process.exitCode=1;}
}
